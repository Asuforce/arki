/**
 * はてなブログのバックアップ（blogsync で取得した Markdown）から、D1 に流す SQL を作る。
 *
 *   npx tsx import-hatena.ts <backup-dir> [--old-host <host>] [--image-map <file>] [--out import.sql]
 *
 * <backup-dir> は `entry/` を含むディレクトリ（例: <your>.hatenablog.com）。
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import matter from "gray-matter";
import { convertBody } from "./hatena.ts";
import { makeExcerpt, slugFromDate, sqlString, toUtcIso } from "./text.ts";

interface Args {
  dir: string;
  oldHost?: string;
  imageMap?: string;
  out: string;
}

function parseArgs(argv: string[]): Args {
  const args: Args = { dir: "", out: "import.sql" };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--old-host") args.oldHost = argv[++i];
    else if (a === "--image-map") args.imageMap = argv[++i];
    else if (a === "--out") args.out = argv[++i];
    else if (!a.startsWith("--") && !args.dir) args.dir = a;
    else throw new Error(`unknown argument: ${a}`);
  }
  if (!args.dir) {
    throw new Error("usage: import-hatena.ts <backup-dir> [--old-host <host>] [--image-map <file>] [--out <file>]");
  }
  return args;
}

function* walk(dir: string): Generator<string> {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* walk(path);
    else if (name.endsWith(".md")) yield path;
  }
}

function main(): void {
  const args = parseArgs(process.argv.slice(2));
  const imageMap = args.imageMap ? (JSON.parse(readFileSync(args.imageMap, "utf8")) as Record<string, string>) : undefined;
  const entryDir = join(args.dir, "entry");

  const statements: string[] = [
    "-- generated by tools/import-hatena.ts. contains post data: do not commit.",
    "DELETE FROM post_categories WHERE post_id IN (SELECT id FROM posts WHERE legacy_url IS NOT NULL);",
    "DELETE FROM posts WHERE legacy_url IS NOT NULL;",
  ];
  const seen = new Set<string>();
  const unknown = new Map<string, string[]>();
  const slugMismatch: string[] = [];
  let posts = 0;
  let drafts = 0;

  for (const file of walk(entryDir)) {
    const slug = relative(entryDir, file).split(sep).join("/").replace(/\.md$/, "");
    if (seen.has(slug)) throw new Error(`duplicate slug: ${slug}`);
    seen.add(slug);

    const { data, content: raw } = matter(readFileSync(file, "utf8"));
    const date = new Date(data.Date as string | Date);
    if (!data.Title || Number.isNaN(date.getTime())) throw new Error(`missing Title or Date: ${file}`);

    // パスは JST の投稿日時のはず。ずれていたら知らせる（`_1` 付きは同時刻の重複なので除く）
    if (slugFromDate(date) !== slug.replace(/_\d+$/, "")) slugMismatch.push(slug);

    const { content, unknown: left } = convertBody(raw.trim(), { oldHost: args.oldHost, imageMap });
    if (left.length) unknown.set(slug, left);

    const status = data.Draft === true ? "draft" : "published";
    if (status === "draft") drafts++;
    const categories: string[] = Array.isArray(data.Category) ? data.Category.map(String) : [];

    statements.push(
      `INSERT INTO posts (slug, title, content, excerpt, status, published_at, legacy_url, slug_fixed, date_fixed) VALUES (` +
        [
          sqlString(slug),
          sqlString(String(data.Title)),
          sqlString(content),
          sqlString(makeExcerpt(content)),
          sqlString(status),
          sqlString(toUtcIso(date)),
          data.URL ? sqlString(String(data.URL)) : "NULL",
          "1",
          "1",
        ].join(", ") +
        `);`,
    );
    for (const name of categories) {
      statements.push(`INSERT OR IGNORE INTO categories (name) VALUES (${sqlString(name)});`);
      statements.push(
        `INSERT OR IGNORE INTO post_categories (post_id, category_id) ` +
          `SELECT p.id, c.id FROM posts p, categories c WHERE p.slug = ${sqlString(slug)} AND c.name = ${sqlString(name)};`,
      );
    }
    posts++;
  }
  statements.push("DELETE FROM categories WHERE id NOT IN (SELECT category_id FROM post_categories);");
  writeFileSync(args.out, statements.join("\n") + "\n");

  console.log(`posts: ${posts} (drafts: ${drafts}) -> ${args.out}`);
  if (slugMismatch.length) console.warn(`path and Date disagree for ${slugMismatch.length} posts: ${slugMismatch.slice(0, 5).join(", ")} ...`);
  if (unknown.size) {
    console.warn(`unconverted notation in ${unknown.size} posts:`);
    for (const [slug, left] of [...unknown].slice(0, 20)) console.warn(`  ${slug}: ${left.join(" | ")}`);
  }
}

main();
